#!/usr/bin/env python3
import sys

def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        return 1

    path = sys.argv[1]

    with open(path, "rb") as f:
        data = f.read()

    out = sys.stdout

    out.write("#pragma once\n")
    out.write(f"// Generated by tools/wad2hpp.py. Do not edit by hand.\n\n")
    out.write("#include <array>\n#include <cstdint>\n\n")
    out.write("namespace wad_data {\n\n")
    out.write(f"inline constexpr std::array<std::uint8_t, {len(data)}> bytes = {{\n")

    for i in range(0, len(data), 24):
        out.write("    " + ",".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",\n")

    out.write("};\n\n}\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())